// Writes the selector grammar's cases (packages/compiler/tests/selector-grammar.ts,
// shared with the compiler's selector differential, so the two cannot drift)
// as generated pages: each grammar case's css on one node in a fixed fixture
// that gives every shape something to match (light and dark ancestors, an
// ancestor with a comma in an attribute, siblings before and after, a twin
// beside it for `& + &`, and p, span, b and a children with the classes the
// grammar names). Forced states go to the styled node only, one at a time,
// and a read while one is forced covers its own fixture. A step flips the
// values read at run time (`p.on`, `p.color`).
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { PACKAGE } from './build.mjs'

/** A props row as JavaScript source: JSON, with a bigint written as its literal. */
const propsSource = row =>
  JSON.stringify(row, (_key, value) => (typeof value === 'bigint' ? `\u0000${value}n` : value)).replace(/"\\u0000(-?\d+n)"/g, '$1')

/** The grammar module: the compiler's, or the copy PARITY_GRAMMAR names (a pinned revision under test). */
const GRAMMAR = process.env.PARITY_GRAMMAR ?? join(PACKAGE, '../compiler/tests/selector-grammar.ts')
/** A JSON file listing grammar case names, to generate only those (the cases a compiler change reroutes); unset, every case. */
const ONLY_CASES = process.env.PARITY_GRAMMAR_CASES

/** Grammar cases per page: few enough pages for a short run, small enough records. */
const PER_PAGE = 48

/** A grammar css object as source; its values are JS source already. */
const cssSource = css =>
  `{ ${Object.entries(css)
    .map(([key, value]) => `${JSON.stringify(key)}: ${value === null ? 'null' : typeof value === 'string' ? value : cssSource(value)}`)
    .join(', ')} }`

/** One grammar case in its fixture; a case's `pair` is a second node, rendered as the first node's child. */
function fixture(key, name, css, pair) {
  const source = cssSource(css)
  const second = pair ? `, Div({ key: 'pair', css: ${cssSource(pair)}, children: Span('pair child', { key: 'c', className: 'b' }) })` : ''
  return `      // ${name.replaceAll('\n', '\\n')}
      Div({ key: '${key}-f', 'data-parity-scope': '', className: 'light', children: Div({ className: 'dark', 'data-x': 'a,b', children: [
        Span('before', { key: 'pre', className: 'a' }),
        Div({ key: '${key}', className: 'a b', 'data-on': '', 'data-parity-force': '', tabIndex: 0, css: ${source}, children: [
          P('p', { key: 'p' }), Span('span', { key: 's', className: 'b' }), B('b', { key: 'b', className: 'c' }), A({ key: 'a', href: '#g', children: 'a' })${second},
        ] }),
        Div({ key: '${key}-twin', className: 'a', css: ${source}, children: 'twin' }),
        Span('after', { key: 'post', className: 'b' }),
        Span('other', { key: 'other', className: 'other' }),
      ] }) }),`
}

/** The page's state: the grammar's run-time props `p`, the first set and then the second after the step, when some case on the page reads them. */
const state = (entries, props) =>
  entries.some(entry => `${cssSource(entry.css)}${entry.pair ? cssSource(entry.pair) : ''}`.includes('p.'))
    ? `  const [on, setOn] = useState(false)\n  const p = on ? ${propsSource(props[1])} : ${propsSource(props[0])}`
    : `  const [, setOn] = useState(false)`

/** One generated grammar page's source. */
function pageSource(index, entries, props) {
  return `// Generated by tests/parity/grammar.mjs from the compiler's selector grammar,
// cases ${index * PER_PAGE + 1}–${index * PER_PAGE + entries.length}. Do not edit. Unchecked by TypeScript:
// the grammar writes values the css types reject on purpose (\`p.on && "blue"\`).
// @ts-nocheck
import { useState, type ReactElement } from 'react'
import { A, B, Button, Div, P, Span } from '@meonode/ui'
import type { CaseMeta } from '../../case.js'

export const meta: CaseMeta = {
  shapes: ['place.css', 'dyn.state', 'env.ssr-hydrate'],
  routes: [],
  generatedFrom: 'grammar',
  force: 'marked',
  forceScope: 'fixture',
  environments: 'base',
  serverModes: ['plain'],
  steps: [{ name: 'flip the run-time values', click: '[data-act="flip"]' }],
}

export function App(): ReactElement {
${state(entries, props)}
  return Div({
    children: [
      Button('flip', { key: 'flip', type: 'button', 'data-act': 'flip', onClick: () => setOn(v => !v) }),
${entries.map((entry, i) => fixture(`g${index}-${i}`, entry.name, entry.css, entry.pair)).join('\n')}
    ],
  } as never).render() as ReactElement
}
`
}

/** Writes every grammar page into `dir` and returns their file names without extension. */
export async function writeGrammarPages(dir) {
  const { cases, PROPS } = await import(pathToFileURL(GRAMMAR).href)
  const only = ONLY_CASES ? new Set(JSON.parse(readFileSync(ONLY_CASES, 'utf8'))) : null
  const all = only ? cases().filter(c => only.has(c.name)) : cases()
  if (only && all.length !== only.size) throw new Error(`PARITY_GRAMMAR_CASES names ${only.size} cases, of which the grammar has ${all.length}`)
  const names = []
  for (let i = 0; i * PER_PAGE < all.length; i++) {
    const name = `grammar-${String(i + 1).padStart(3, '0')}`
    writeFileSync(join(dir, `${name}.case.ts`), pageSource(i, all.slice(i * PER_PAGE, (i + 1) * PER_PAGE), PROPS))
    names.push(name)
  }
  return names
}
