/** Every selector @webref/css lists, by name. */
export async function webrefSelectors() {
  const require = createRequire(join(PACKAGE, 'package.json'))
  const webref = await import(require.resolve('@webref/css'))
  return (await webref.default.listAll()).selectors.map(s => s.name)
}

/** Webref selectors with no inventory entry, and entries for names it does not list among the webref ones. */
export async function selectorGaps() {
  const listed = new Set(SELECTORS.map(s => s.name))
  return (await webrefSelectors()).filter(name => !listed.has(name))
}
