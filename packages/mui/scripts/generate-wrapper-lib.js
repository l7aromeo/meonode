const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const ROOT = path.resolve(__dirname, '..')
const SRC_DIR = path.join(ROOT, 'src')
const LIB_DIR = path.join(SRC_DIR, 'lib')
const require = createRequire(import.meta.url)
const WRAPPED_CACHE_PATH = path.join(__dirname, 'wrapped-mui.json')
const EXCLUDED_CACHE_PATH = path.join(__dirname, 'excluded-mui.json')
const MAX_GENERATE_PASSES = 8
const GENERATED_FILE_BANNER = '// Generated by scripts/generate-wrapper-lib.js — do not edit by hand.\n'

const CHECK_STATS = {
  keepExport: {
    total: 0,
    kept: 0,
    rejected: 0,
    reasons: {},
  },
  runtime: {
    total: 0,
    kept: 0,
    rejected: 0,
    reasons: {},
  },
  ts: {
    wrappedHits: 0,
    excludedHits: 0,
    codes: {},
  },
}

function incReason(bucket, reason) {
  bucket.reasons[reason] = (bucket.reasons[reason] ?? 0) + 1
}

function incCode(code) {
  CHECK_STATS.ts.codes[code] = (CHECK_STATS.ts.codes[code] ?? 0) + 1
}

